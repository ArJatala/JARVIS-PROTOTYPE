import os
import subprocess
import pyttsx3
import speech_recognition as sr
from faster_whisper import WhisperModel
import requests
from flask import Flask, jsonify
from flask_cors import CORS

app = Flask(__name__)
CORS(app)

# 1. Initialize TTS Engine (Offline Voice Output)
tts = pyttsx3.init()
tts.setProperty('rate', 180)
voices = tts.getProperty('voices')
if voices:
    tts.setProperty('voice', voices[0].id)

# 2. Initialize Whisper STT (CPU Multi-Threading for 11th Gen i7)
print("Loading Whisper STT engine (CPU Optimized)...")
whisper_model = WhisperModel(
    "tiny.en", 
    device="cpu", 
    compute_type="int8", 
    cpu_threads=8
)

def speak(text):
    tts.say(text)
    tts.runAndWait()

def ask_ollama(prompt):
    """Routes unrecognized queries to local Llama 3.2 1B."""
    url = "http://localhost:11434/api/generate"
    payload = {
        "model": "llama3.2:1b",
        "prompt": f"You are J.A.R.V.I.S, a direct and ultra-efficient AI assistant. Answer in 1 to 2 concise sentences. User: {prompt}",
        "stream": False
    }
    try:
        response = requests.post(url, json=payload, timeout=10).json()
        return response.get('response', 'No response generated.')
    except Exception as e:
        return f"Local LLM connection failed: {e}"

def execute_pc_command(text):
    """Command Router for OS Navigation & Automation"""
    cmd = text.lower()
    
    if "open notepad" in cmd:
        subprocess.Popen("notepad.exe")
        return "Notepad initialized."
        
    elif "create log" in cmd or "create a file" in cmd:
        desktop_path = os.path.join(os.path.expanduser("~"), "Desktop", "jarvis_log.txt")
        with open(desktop_path, "w") as f:
            f.write("System log generated by J.A.R.V.I.S.\n")
        return "Log file written to desktop."
        
    elif "system status" in cmd:
        return "CPU core threads active. Memory utilization nominal."
        
    else:
        # Fallback to local LLM logic
        return ask_ollama(text)

@app.route('/api/listen', methods=['POST'])
def listen_and_process():
    """Captures microphone input and computes response."""
    recognizer = sr.Recognizer()
    audio_file = "temp_audio.wav"
    
    try:
        with sr.Microphone() as source:
            print("\n[MIC ACTIVE] Speak now...")
            recognizer.adjust_for_ambient_noise(source, duration=0.5)
            audio = recognizer.listen(source, timeout=4, phrase_time_limit=8)
            
            with open(audio_file, "wb") as f:
                f.write(audio.get_wav_data())
                
        # Transcribe audio using faster-whisper on CPU
        segments, _ = whisper_model.transcribe(audio_file, beam_size=1)
        user_text = "".join([segment.text for segment in segments]).strip()
        
        if not user_text:
            return jsonify({"user": "[Unclear Audio]", "jarvis": "I could not interpret that audio signal."})
            
        # Execute logic or run LLM inference
        jarvis_response = execute_pc_command(user_text)
        
        # Audio feedback
        speak(jarvis_response)
        
        return jsonify({"user": user_text, "jarvis": jarvis_response})
        
    except sr.WaitTimeoutError:
        return jsonify({"user": "[Timeout]", "jarvis": "No voice activity detected within timeout limit."})
    except Exception as e:
        print(f"Error: {e}")
        return jsonify({"user": "Error", "jarvis": f"Execution error: {str(e)}"})

